// Slim catalogue index, generated at build time from the same JSON the admin
// edits — imported as `virtual:catalog-index`.
//
// Why this exists: the header is mounted on every route, and Navbar,
// MobileNavSheet and data/navigation.js all imported the FULL tours.json
// (136KB) and packages.json (141KB) to build a search dropdown and a menu
// rail. A static import from an always-mounted component forces the whole
// dataset into the eager index-*.js chunk, so every visitor downloaded every
// tour description, FAQ, gallery list and map waypoint before the first paint
// — on the homepage, on the contact page, everywhere.
//
// The menus need nine fields per tour. This emits exactly those, ~5KB for the
// pair, and the full JSON stays in the route chunks that genuinely need it
// (TourDetail, Tours, PackageDetail…), where it loads lazily.
//
// It is generated rather than hand-maintained on purpose: a checked-in slim
// copy would drift the moment someone renamed a tour in /admin. This reads
// the JSON at build time and, in dev, regenerates whenever the admin writes
// to it.

import fs from 'node:fs'
import path from 'node:path'

// Two modules, not one with four exports. The nav index is imported by the
// always-eager Navbar and the cards by lazy route chunks; from a single module
// Rollup cannot split them — the module lands in the eager chunk and takes
// every used export with it, which put the cards back in index-*.js.
const NAV_ID = 'virtual:catalog-index'
const CARDS_ID = 'virtual:catalog-cards'
const RESOLVED = { [NAV_ID]: '\0' + NAV_ID, [CARDS_ID]: '\0' + CARDS_ID }
const SOURCES = ['tours.json', 'packages.json']

// Keep these in step with what the nav actually reads:
//   navigation.js  tourLink()     → slug, title, duration, price, hero
//                  categoryPlace()→ category, extraCategories (via tourCategories)
//                  journeyLink()  → slug, name, duration, price/priceWithout, heroImage
//                  journeysThroughCities() → days[].city
//   Navbar / MobileNavSheet search → id, title, badge, duration, price, slug
const slimTour = (t) => ({
  id: t.id,
  slug: t.slug,
  title: t.title,
  duration: t.duration,
  price: t.price,
  hero: t.hero,
  badge: t.badge,
  category: t.category,
  extraCategories: t.extraCategories,
})

const slimJourney = (p) => ({
  slug: p.slug,
  name: p.name,
  title: p.title,
  duration: p.duration,
  price: p.price,
  priceWithout: p.priceWithout,
  heroImage: p.heroImage,
  hero: p.hero,
  // Only the city per day — journeysThroughCities() matches on it.
  days: (p.days || []).map((d) => ({ city: d.city })),
})

// The card index is a DENYLIST, unlike the nav index above: a card gets every
// field except the long-form ones only a detail page renders. Listing surfaces
// have grown a field before now (badgeStyle, countries, languages…), and an
// allowlist would have dropped them silently — here anything new is carried
// through by default. These names are the ~85% of the payload that never
// appears on a card.
const TOUR_DETAIL_ONLY = [
  'description', 'faqs', 'accessibility', 'mapWaypoints', 'gallery', 'includes',
  'excludes', 'rightFor', 'notRightFor', 'fitnessNote', 'extras', 'journalPosts',
  'detailHero', 'meetingPoint',
]
const JOURNEY_DETAIL_ONLY = [
  'days', 'importantInfo', 'breakdown', 'activities', 'about', 'suitability',
  'inclusions', 'exclusions', 'mapWaypoints', 'fitnessNotes', 'accessibility',
]

const omit = (obj, keys) => {
  const out = {}
  for (const [k, v] of Object.entries(obj)) if (!keys.includes(k)) out[k] = v
  return out
}

// TourCard documents that it takes "the highlights array or a pre-computed
// count" and only ever reads .length, so cards carry the number (18KB of
// landmark copy for a "6 highlights" label otherwise).
const cardTour = (t) => ({
  ...omit(t, TOUR_DETAIL_ONLY),
  highlights: (t.highlights || []).length,
})

const cardJourney = (p) => omit(p, JOURNEY_DETAIL_ONLY)

export default function catalogIndex() {
  let dataDir

  const read = (file) => JSON.parse(fs.readFileSync(path.join(dataDir, file), 'utf8'))
  const header = '// Generated by scripts/vite-plugin-catalog-index.js — do not edit.'

  const generate = (id) => {
    const tours = read('tours.json')
    const journeys = read('packages.json')
    if (id === RESOLVED[NAV_ID]) {
      return [
        header,
        `export const tourIndex = ${JSON.stringify(tours.map(slimTour))}`,
        `export const journeyIndex = ${JSON.stringify(journeys.map(slimJourney))}`,
        '',
      ].join('\n')
    }
    return [
      header,
      `export const tourCards = ${JSON.stringify(tours.map(cardTour))}`,
      `export const journeyCards = ${JSON.stringify(journeys.map(cardJourney))}`,
      '',
    ].join('\n')
  }

  return {
    name: 'catalog-index',
    configResolved(config) {
      dataDir = path.join(config.root, 'src', 'data')
    },
    resolveId(id) {
      return RESOLVED[id]
    },
    load(id) {
      if (id === RESOLVED[NAV_ID] || id === RESOLVED[CARDS_ID]) return generate(id)
    },
    configureServer(server) {
      // /admin writes straight to these files; without this the menus would
      // keep serving the copy generated when the dev server booted.
      const onChange = (file) => {
        if (!SOURCES.some((name) => file.endsWith(name))) return
        let hit = false
        for (const resolved of Object.values(RESOLVED)) {
          const mod = server.moduleGraph.getModuleById(resolved)
          if (mod) {
            server.moduleGraph.invalidateModule(mod)
            hit = true
          }
        }
        if (hit) server.ws.send({ type: 'full-reload' })
      }
      server.watcher.on('change', onChange)
      server.watcher.on('add', onChange)
    },
  }
}
